import base64, io, os, sys
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables._g_l_y_f import Glyph, GlyphComponent
from fontTools.subset import Subsetter, Options

# Source Sans 3 and Source Serif 4 ship superscript glyphs only for 1, 2 and 3.
# The exports print exponents such as 10^-5, so the rest are synthesised here as
# scaled, raised copies of the normal digits. Doing it in the font keeps one
# formatted string working in the interface, the PDF and the Excel export.
SUPERSCRIPTS = {
    0x2070: '0', 0x00b9: '1', 0x00b2: '2', 0x00b3: '3', 0x2074: '4',
    0x2075: '5', 0x2076: '6', 0x2077: '7', 0x2078: '8', 0x2079: '9',
    0x207b: '-',
}
SUP_SCALE = 0.62
SUP_RAISE = 0.33


def add_superscripts(font):
    upem = font['head'].unitsPerEm
    glyf, hmtx, cmap_table = font['glyf'], font['hmtx'], font['cmap']
    base_cmap = font.getBestCmap()
    added = []
    for code, char in SUPERSCRIPTS.items():
        src = base_cmap.get(ord(char))
        if src is None or src not in glyf:
            continue
        name = 'sup.u%04X' % code
        comp = GlyphComponent()
        comp.glyphName = src
        comp.x, comp.y = 0, int(round(SUP_RAISE * upem))
        comp.transform = [[SUP_SCALE, 0], [0, SUP_SCALE]]
        comp.flags = 0x0002  # args are xy values
        glyph = Glyph()
        glyph.numberOfContours = -1
        glyph.components = [comp]
        # glyf's __setitem__ also extends its glyphOrder, so no manual append.
        glyf[name] = glyph
        adv, lsb = hmtx[src]
        hmtx[name] = (int(round(adv * SUP_SCALE)), int(round(lsb * SUP_SCALE)))
        added.append((code, name))
    font.setGlyphOrder(list(glyf.glyphOrder))
    for sub in cmap_table.tables:
        if sub.isUnicode():
            for code, name in added:
                sub.cmap[code] = name
    return [name for _, name in added]

import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'node_modules', '@fontsource')
OUT = os.path.join(ROOT, 'src', 'pdf', 'fonts')

# Latin-1 plus the punctuation and symbols the interface and exports use.
EXTRA = 'ÁÉÍÓÚÜÑáéíóúüñ€—–’‘“”…×≥≤°µ†\u00a0\u207b\u2070\u00b9\u00b2\u00b3\u2074\u2075\u2076\u2077\u2078\u2079'
chars = set(chr(c) for c in range(0x20, 0x7f)) | set(EXTRA)

FACES = [
  ('SourceSerif4-SemiBold', os.path.join(SRC, 'source-serif-4', 'files', 'source-serif-4-latin-600-normal.woff')),
  ('SourceSans3-Regular',    os.path.join(SRC, 'source-sans-3', 'files', 'source-sans-3-latin-400-normal.woff')),
  ('SourceSans3-SemiBold',   os.path.join(SRC, 'source-sans-3', 'files', 'source-sans-3-latin-600-normal.woff')),
]

lines = ["// Generated by scripts/build-pdf-fonts.py from the self-hosted @fontsource",
         "// packages (Source Serif 4 600, Source Sans 3 400 and 600), subset to the",
         "// characters this tool uses and converted to TTF for jsPDF. Do not edit by hand.",
         ""]
for name, path in FACES:
    f = TTFont(path)
    opt = Options()
    opt.layout_features = ['kern','liga']
    opt.name_IDs = ['*']
    opt.name_legacy = True
    opt.notdef_outline = True
    opt.recalc_bounds = True
    opt.drop_tables = ['DSIG']
    s = Subsetter(options=opt)
    s.populate(text=''.join(sorted(chars)))
    s.subset(f)
    add_superscripts(f)
    f.flavor = None
    buf = io.BytesIO()
    f.save(buf)
    raw = buf.getvalue()
    b64 = base64.b64encode(raw).decode()
    key = name.replace('-', '_').upper()
    lines.append(f"export const {key} = {{")
    lines.append(f"  file: '{name}.ttf',")
    lines.append(f"  base64:")
    for i in range(0, len(b64), 108):
        lines.append(f"    '{b64[i:i+108]}' +")
    lines[-1] = lines[-1][:-2]
    lines.append(f",\n}}\n")
    print(f"{name}: {len(raw)} bytes raw, {len(b64)} base64")

open(os.path.join(OUT, 'embedded.js'), 'w').write("\n".join(lines))
print("written")
